
package model;

import java.math.BigDecimal;
import java.sql.Timestamp;

public class Stock {

    private int stockId;
    private int productId;

    private Integer ownerCompanyId;
    private Integer shipmentId;
    private Integer containerId;

    private String sku;
    private String productName;
    private String shipmentNo;
    private String containerNumber;

    private BigDecimal quantity = BigDecimal.ZERO;
    private BigDecimal reservedQty = BigDecimal.ZERO;
    private BigDecimal damagedQty = BigDecimal.ZERO;
    private BigDecimal availableQty = BigDecimal.ZERO;

    private Timestamp lastUpdated;

    public int getStockId() {
        return stockId;
    }

    public void setStockId(int stockId) {
        this.stockId = stockId;
    }

    public int getProductId() {
        return productId;
    }

    public void setProductId(int productId) {
        this.productId = productId;
    }

    public Integer getOwnerCompanyId() {
        return ownerCompanyId;
    }

    public void setOwnerCompanyId(Integer ownerCompanyId) {
        this.ownerCompanyId = ownerCompanyId;
    }

    public Integer getShipmentId() {
        return shipmentId;
    }

    public void setShipmentId(Integer shipmentId) {
        this.shipmentId = shipmentId;
    }

    public Integer getContainerId() {
        return containerId;
    }

    public void setContainerId(Integer containerId) {
        this.containerId = containerId;
    }

    public String getSku() {
        return sku;
    }

    public void setSku(String sku) {
        this.sku = sku;
    }

    public String getProductName() {
        return productName;
    }

    public void setProductName(String productName) {
        this.productName = productName;
    }

    public String getShipmentNo() {
        return shipmentNo;
    }

    public void setShipmentNo(String shipmentNo) {
        this.shipmentNo = shipmentNo;
    }

    public String getContainerNumber() {
        return containerNumber;
    }

    public void setContainerNumber(String containerNumber) {
        this.containerNumber = containerNumber;
    }

    public BigDecimal getQuantity() {
        return quantity;
    }

    public void setQuantity(BigDecimal quantity) {
        this.quantity = quantity;
    }

    public BigDecimal getReservedQty() {
        return reservedQty;
    }

    public void setReservedQty(BigDecimal reservedQty) {
        this.reservedQty = reservedQty;
    }

    public BigDecimal getDamagedQty() {
        return damagedQty;
    }

    public void setDamagedQty(BigDecimal damagedQty) {
        this.damagedQty = damagedQty;
    }

    public BigDecimal getAvailableQty() {
        return availableQty;
    }

    public void setAvailableQty(BigDecimal availableQty) {
        this.availableQty = availableQty;
    }

    public Timestamp getLastUpdated() {
        return lastUpdated;
    }

    public void setLastUpdated(Timestamp lastUpdated) {
        this.lastUpdated = lastUpdated;
    }

    public boolean isReserved() {
        return reservedQty != null
                && reservedQty.signum() > 0;
    }
}
